export type CopyKey = keyof typeof EN;

const CATALOGS: Record<string, typeof EN> = { en: EN };

export function t(lang: string, key: CopyKey, vars?: Record<string, string | number>): string {
   const raw = (CATALOGS[lang] ?? EN)[key];
   if (vars == null) {
      return raw;
   }
   return raw.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export function languageOf(code: string | undefined): string {
   const base = (code ?? "").trim().toLowerCase().split("-")[0] ?? "";
   return base === "" ? "en" : base;
}
